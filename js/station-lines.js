const STATION_LINES_MIN_ZOOM = 15; // このズーム以上で、札を出す

// 駅名 → その名前の駅の一覧(同じ名前の駅が、別の場所にあることもあるため)
const railStationsByName = new Map();
railStations.forEach((s) => {
  if (!railStationsByName.has(s[2])) railStationsByName.set(s[2], []);
  railStationsByName.get(s[2]).push(s);
});

map.createPane("stationLinesPane");
map.getPane("stationLinesPane").style.zIndex = 440; // 地図の絵より上、目印(450)とお店のピン(600)より下
map.getPane("stationLinesPane").style.pointerEvents = "none";

const stationLineMarkers = new Map(); // 「駅名|緯度|経度」→ 表示中の札

function stationLinesIcon(opIdx) {
  const chips = opIdx
    .map((i) => railOps[i])
    .filter(Boolean)
    .map((o) => `<span class="lm-line">${esc(currentLang === "ja" ? o.ja : o.en)}</span>`)
    .join("");
  return L.divIcon({ className: "station-lines-icon", html: `<span class="station-lines">${chips}</span>`, iconSize: null });
}

// 地図に出ている駅を調べて、札を付け直す
function updateStationLines() {
  const gl = typeof vectorMaps !== "undefined" ? vectorMaps[0] : null;
  const z = map.getZoom();
  const seen = new Set();
  if (gl && z >= STATION_LINES_MIN_ZOOM) {
    let feats = [];
    try {
      feats = gl.queryRenderedFeatures({ layers: ["poi_label"] });
    } catch (e) {
      feats = [];
    }
    feats.forEach((f) => {
      if (!f.geometry || f.geometry.type !== "Point") return;
      const name = String(f.properties.name || "").replace(/駅$/, "");
      const cands = railStationsByName.get(name);
      if (!cands) return;
      const [lng, lat] = f.geometry.coordinates;
      // 同じ名前の駅のうち、いちばん近いもの(800m 以内)を使う
      let best = null;
      let bestD = Infinity;
      cands.forEach((s) => {
        const d = map.distance([lat, lng], [s[0], s[1]]);
        if (d < bestD) {
          bestD = d;
          best = s;
        }
      });
      if (!best || bestD > 800) return;
      const key = `${name}|${lat.toFixed(4)}|${lng.toFixed(4)}`;
      if (seen.has(key)) return;
      seen.add(key);
      if (!stationLineMarkers.has(key)) {
        const m = L.marker([lat, lng], { pane: "stationLinesPane", interactive: false, keyboard: false, icon: stationLinesIcon(best[3]) });
        m.addTo(map);
        stationLineMarkers.set(key, { marker: m, ops: best[3] });
      }
    });
  }
  // 地図から消えた駅の札は、外す
  stationLineMarkers.forEach((v, key) => {
    if (!seen.has(key)) {
      map.removeLayer(v.marker);
      stationLineMarkers.delete(key);
    }
  });
  map.getContainer().dataset.lang = currentLang;
}

let stationLinesTimer = null;
function scheduleStationLines() {
  clearTimeout(stationLinesTimer);
  stationLinesTimer = setTimeout(updateStationLines, 400);
}
map.on("zoomend moveend", scheduleStationLines);
// 背景の地図の描画が終わったときにも調べ直す(読み込みに時間がかかったとき用)
(function watchGl() {
  const gl = typeof vectorMaps !== "undefined" ? vectorMaps[0] : null;
  if (gl) gl.on("idle", scheduleStationLines);
  else setTimeout(watchGl, 1000);
})();

// 言語を切り替えたら、札の文字も切り替える
document.getElementById("lang-select").addEventListener("change", () => {
  setTimeout(() => {
    stationLineMarkers.forEach((v) => v.marker.setIcon(stationLinesIcon(v.ops)));
    map.getContainer().dataset.lang = currentLang;
  }, 0);
});
